def list_timezones():
    yield ('', "Select a Timezone")
    common = set(pytz.common_timezones)
    rest = set(pytz.all_timezones) - common
    sf = lambda t: (not t.startswith('America/'), t != 'UTC', t)
    for t in sorted(common | rest, key=sf):
        yield (t, t)


class ValidateRequiredIf:
    def __init__(self, other_name: str, message: str="Must be present if {other_title} is present"):
        self.other_name = other_name
        self.message = message

    def __call__(self, form, field):
        other_field = getattr(form, self.other_name)
        if other_field.data and not field.data:
            raise ValidationError(self.message.replace('{other_title}', other_field.label.text))


class LoginForm(FlaskForm):
    username_or_email = StringField('Username or Email', validators=[DataRequired()])
    password = PasswordField('Password', validators=[DataRequired()])
    submit = SubmitField('Log In')

    def validate_on_submit(self):
        if super().validate_on_submit():
            # Custom implementation to avoid leaking data via timing
            user = None
            valid_user = False
            try:
                user = User.query.filter(
                    User.username.like(self.username_or_email.data)
                    | User.email.like(self.username_or_email.data)
                ).one()
                valid_user = True
            except NoResultFound:
                user = User.query.first()
            except MultipleResultsFound:
                logger.error("Found more than one user matching %s", self.username_or_email.data)

            if user:
                if user.password == self.password.data:
                    if valid_user:
                        return user
            # Return None if we checked, to indicate invalid info
            return None
        return False



